import { PLANT_TOPOLOGY } from '../src/model/topology';
import { createNetworkState, spinUpNetwork } from '../src/sim/networkEngine';
const s = spinUpNetwork(createNetworkState(PLANT_TOPOLOGY, { seed: 42, model: 'asm1' }), PLANT_TOPOLOGY, 30);
const get = (id: string) => s.reactors.find(r => r.id === id)!;
const ana = get('anaerobic'), anx = get('anoxic'), ae3 = get('aerobic3');
const Q = s.influent.flow, ir = Q * s.controls.internalRecirc, qAna = Q;
const mixedNO3 = (ir * ae3.no3 + qAna * ana.no3) / (ir + qAna);
console.log('ana NO3', ana.no3.toFixed(2), 'aerobic3 NO3', ae3.no3.toFixed(2), 'anoxic NO3 actual', anx.no3.toFixed(2), 'dilution-only mixed', mixedNO3.toFixed(2));
const mixedXBH = (ir * (ae3.asm1?.X_B_H ?? 0) + qAna * (ana.asm1?.X_B_H ?? 0)) / (ir + qAna);
console.log('mixed XBH from IR+ana', mixedXBH.toFixed(1), 'anoxic XBH actual', anx.asm1?.X_B_H?.toFixed(1));
