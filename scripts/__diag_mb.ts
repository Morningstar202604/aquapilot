import { PLANT_TOPOLOGY } from '../src/model/topology';
import { createNetworkState, spinUpNetwork } from '../src/sim/networkEngine';

const s = spinUpNetwork(createNetworkState(PLANT_TOPOLOGY, { seed: 42, model: 'asm1' }), PLANT_TOPOLOGY, 30);
const Q = s.influent.flow;
const ras = s.controls.rasRatio;
const was = s.controls.wasRatio;
const Qr = Q * ras;
const Qw = Q * was;
const Qf = Q * (1 + Math.max(ras, 0.3));
const Qu = Qr + Qw;
const xBio = (s.biomassKg * 1000) / s.volume.bio;
const inKg = Qf * xBio / 1000;
const outKg = (Qu * s.clarifier.xRas + (Qf - Qu) * s.clarifier.xEff) / 1000;
console.log({Q: Q.toFixed(0), Qf: Qf.toFixed(0), Qu: Qu.toFixed(0), xBio: xBio.toFixed(0), xRas: s.clarifier.xRas.toFixed(0), xEff: s.clarifier.xEff.toFixed(1)});
console.log('settler in kg/d', inKg.toFixed(0), 'out kg/d', outKg.toFixed(0), 'ratio', (outKg/inKg).toFixed(3));
console.log('reactor biomass kg', s.biomassKg.toFixed(0), 'settler sludge kg', s.clarifier.sludgeMassKg.toFixed(0));
console.log('reported SRT', s.srtDays.toFixed(1));
const wasKgDay = Qw * 24 * (s.biomassKg * 1000 / s.volume.bio) / 1000;
const effKgDay = (Q - Qw) * 24 * s.clarifier.xEff / 1000;
console.log('wasKgDay', wasKgDay.toFixed(0), 'effKgDay', effKgDay.toFixed(0), 'true SRT (reactor+settler)/(was+eff)', ((s.biomassKg + s.clarifier.sludgeMassKg) / (wasKgDay + effKgDay)).toFixed(1));
