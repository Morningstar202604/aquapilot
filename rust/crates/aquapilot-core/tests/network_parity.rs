#[test]
fn network_48h_matches_ts_golden() {
    let reactors = vec![
        Reactor {
            id: "anaerobic".into(),
            kind: ReactorKind::Anaerobic,
            volume: 3000.0,
            state: state(INITIAL[0]),
            kla: 0.0,
            integral: 0.0,
            o2_demand: 0.0,
        },
        Reactor {
            id: "anoxic".into(),
            kind: ReactorKind::Anoxic,
            volume: 4500.0,
            state: state(INITIAL[1]),
            kla: 0.0,
            integral: 0.0,
            o2_demand: 0.0,
        },
        Reactor {
            id: "aerobic1".into(),
            kind: ReactorKind::Aerobic,
            volume: 5750.0,
            state: state(INITIAL[2]),
            kla: 0.0,
            integral: 0.0,
            o2_demand: 0.0,
        },
        Reactor {
            id: "aerobic2".into(),
            kind: ReactorKind::Aerobic,
            volume: 5750.0,
            state: state(INITIAL[3]),
            kla: 0.0,
            integral: 0.0,
            o2_demand: 0.0,
        },
        Reactor {
            id: "aerobic3".into(),
            kind: ReactorKind::Aerobic,
            volume: 5750.0,
            state: state(INITIAL[4]),
            kla: 0.0,
            integral: 0.0,
            o2_demand: 0.0,
        },
    ];
    let edges = vec![
        Edge {
            from: None,
            to: 0,
            flow: 1546.0,
            recycle: Recycle::None,
        },
        Edge {
            from: Some(4),
            to: 0,
            flow: 454.0,
            recycle: Recycle::Ras,
        },
        Edge {
            from: Some(0),
            to: 1,
            flow: 2000.0,
            recycle: Recycle::None,
        },
        Edge {
            from: Some(1),
            to: 2,
            flow: 2000.0,
            recycle: Recycle::None,
        },
        Edge {
            from: Some(2),
            to: 3,
            flow: 2000.0,
            recycle: Recycle::None,
        },
        Edge {
            from: Some(3),
            to: 4,
            flow: 2000.0,
            recycle: Recycle::None,
        },
    ];
    let mut net = Network::new(reactors, edges);
    let inf = Influent {
        flow: 1546.0,
        cod: 312.0,
        nh: 31.5,
        tn: 44.0,
        tp: 4.6,
        ss: 184.0,
        alkalinity: 8.0,
    };
    let opts = StepOptions {
        dt_h: 0.5,
        temperature_c: 20.0,
        bio_p: true,
        suppression: 1.0,
        do_setpoint: 2.0,
        aeration_capacity: 0.976,
    };
    for _ in 0..48 {
        net.step(inf, 4428.0, &Params::default(), opts);
    }
    for (i, reactor) in net.reactors.iter().enumerate() {
        for (c, (got, want)) in reactor
            .state
            .v
            .iter()
            .zip(EXPECTED_FINAL[i].iter())
            .enumerate()
        {
            assert!(
                (got - want).abs() <= 1e-9,
                "reactor {i} component {c}: got {got}, want {want}"
            );
        }
    }
}
